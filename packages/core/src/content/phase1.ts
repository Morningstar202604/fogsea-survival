/**
 * 将第一阶段内容合并到主内容包中
 * @param content 主内容包
 * @returns 合并后的内容包
 */
export function mergePhase1Content(content: any): any {
  // 合并场景
  content.storyline.scenes = {
    ...content.storyline.scenes,
    ...PHASE1_SCENES,
  };

  // 合并事件
  if (!content.events) content.events = [];
  content.events = [...content.events, ...PHASE1_EVENTS];

  return content;
}
